    private ZombiesWaves() {}

    /** 该回合各波时间（秒）；超出范围返回 null。 */
    public static int[] getWaves(int round) {
        if (round < 1 || round > ALIEN_ARCADIUM.length) {
            return null;
        }
        return ALIEN_ARCADIUM[round - 1];
    }

    public static boolean has(int round) {
        return getWaves(round) != null;
    }

    /**
     * 当前进行到第几波（0-based）。
     * @param elapsedSec 回合开始至今秒数
     * @return 已开始的最后一波下标；-1 表示第一波还没到
     */
    public static int currentWaveIndex(int[] waves, double elapsedSec) {
        int idx = -1;
        for (int i = 0; i < waves.length; i++) {
            if (elapsedSec >= waves[i]) {
                idx = i;
            } else {
                break;
            }
        }
        return idx;
    }

    /** 距下一波还有几秒；已是最后一波返回 -1。 */
    public static double secondsToNextWave(int[] waves, double elapsedSec) {
        for (int time : waves) {
            if (time > elapsedSec) {
                return time - elapsedSec;
            }
        }
        return -1;
    }
